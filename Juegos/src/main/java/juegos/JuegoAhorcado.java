	public void iniciarJuego(String palabra) {
		adivinado = "";
		if (palabra.length() < 4) {
			JOptionPane.showMessageDialog(this, "La palabra es demasiado corta(mínimo 4 letras).");
			return;
		} else if (palabra.length() > 20) {
			JOptionPane.showMessageDialog(this, "La palabra es demasiado larga(máximo 20 letras).");
			return;
		}
		palabra = palabra.toUpperCase();
		palabraOculta = palabra;
		for (int i = 0; i < palabra.length(); i++) {
			adivinado += "-";
		}
		mostrarHuecos();
		HuecoPalabra.setVisible(false);
		Reset.setEnabled(false);
		BotonJugar.setEnabled(false);
		inicializarBotones(true);
		Vidas.setText("      ");
		for (int i = 6; i > intentosFallidos; i--) {
			Vidas.setText(Vidas.getText() + "❤ ");
		}
	}

	private void letraPulsada(JButton b) {
		b.setEnabled(false);
		comprobarLetra(b.getText().charAt(0));
	}

	public void comprobarLetra(char letra) {
		boolean acierto = false;
		for (int i = 0; i < palabraOculta.length(); i++) {
			if (palabraOculta.charAt(i) == letra) {
				adivinado = adivinado.substring(0, i) + letra + adivinado.substring(i + 1);
				acierto = true;
			}
		}
		if (!acierto) {
			Fallos.setText(Fallos.getText() + letra + " ");
			intentosFallidos++;
			Vidas.setText("      ");
			for (int i = 6; i > intentosFallidos; i--) {
				Vidas.setText(Vidas.getText() + "❤ ");
			}
		}
		mostrarHuecos();
		comprobarVictoria();
	}

	public void mostrarHuecos() {
		String oculto = "";
		for (int i = 0; i < palabraOculta.length(); i++) {
			if (palabraOculta.charAt(i) == ' ') {
				oculto = oculto + "   ";
				adivinado = adivinado.substring(0, i) + ' ' + adivinado.substring(i + 1);
			} else if (adivinado.charAt(i) != '-') {
				oculto = oculto + palabraOculta.charAt(i);
			} else {
				oculto = oculto + "_ ";
			}
		}
		Rayas.setText(oculto);
		Rayas.setFont(new Font("Arial", Font.BOLD, 24));
	}

	public void comprobarVictoria() {
		if (adivinado.equalsIgnoreCase(palabraOculta)) {
			Reset.setEnabled(true);
			inicializarBotones(false);
			if (turno == 1) {
				ganadas[0]++;
				turno++;
			} else {
				ganadas[1]++;
				turno = 1;
			}
			turno++;
			JOptionPane.showMessageDialog(this, "VICTORIA DEL JUGADOR QUE ADIVINA.");
		} else if (intentosFallidos == 6) {
			Reset.setEnabled(true);
			inicializarBotones(false);
			if (turno == 1) {
				ganadas[1]++;
				turno++;
			} else {
				ganadas[0]++;
				turno = 1;
			}
			Rayas.setText(palabraOculta);
			JOptionPane.showMessageDialog(this, "DERROTA DEL JUGADOR QUE ADIVINA.");
		}
		Ganadas1.setText("J1: " + ganadas[0]);
		Ganadas2.setText("J2: " + ganadas[1]);
	}

	public void reiniciarJuego() {
		palabraOculta = "";
		intentosFallidos = 0;
		adivinado = "";
		Fallos.setText("FALLOS: ");
		HuecoPalabra.setText("");
		HuecoPalabra.setVisible(true);
		Rayas.setText("");
		Reset.setEnabled(false);
		BotonJugar.setEnabled(true);
	}

	public void comprobarGanador() {
		if (ganadas[0] > ganadas[1]) {
			JOptionPane.showMessageDialog(this, "EL GANADOR DE LA PARTIDA HA SIDO EL JUGADOR 1.");
		} else if (ganadas[0] == ganadas[1]) {
			JOptionPane.showMessageDialog(this, "LA PARTIDA ACABÓ EN EMPATE.");
		} else {
			JOptionPane.showMessageDialog(this, "EL GANADOR DE LA PARTIDA HA SIDO EL JUGADOR 2.");
		}
		System.exit(0);
	}


    public void añadirFicha(JButton boton, int fila, int col) {
        Turno.setForeground(Color.black);
        if (juegoTerminado) {
            Turno.setText("EL JUEGO YA HA TERMINADO. GRACIAS POR JUGAR");
            return;
        }
        if (tablero[fila][col] == 0) {
            int jugadorActual = turno;
            switch (turno) {
                case 1:
                    tablero[fila][col] = 1;
                    boton.setText("X");
                    boton.setForeground(Color.blue);
                    turno = 2;
                    Turno.setText("TURNO JUGADOR 2");
                    break;
                case 2:
                    tablero[fila][col] = 2;
                    boton.setText("O");
                    boton.setForeground(Color.red);
                    turno = 1;
                    Turno.setText("TURNO JUGADOR 1");
                    break;
                default:
                    boton.setText("");
                    break;
            }
            boton.setFont(new Font("Arial", Font.BOLD, 100));
            ganador(jugadorActual);
        } else {
            Turno.setForeground(Color.red);
            Turno.setText("ERROR. ESA CASILLA YA ESTÁ OCUPADA");
        }
    }

    public boolean empate() {
        int total = 0;
        for (int i = 0; i < tablero.length; i++) {
            for (int j = 0; j < tablero[i].length; j++) {
                if (tablero[i][j] != 0) {
                    total++;
                }
            }
        }

        if (total == 9) {
            return true;
        }
        return false;
    }

    public boolean comprobarVictoria() {
        //Comprobar filas
        for (int i = 0; i < tablero.length; i++) {
            if (tablero[i][0] != 0 && tablero[i][0] == tablero[i][1] && tablero[i][2] == tablero[i][0]) {
                return true;
            }
        }
        //Comprobar Columnas
        for (int i = 0; i < tablero[0].length; i++) {
            if (tablero[0][i] != 0 && tablero[0][i] == tablero[1][i] && tablero[2][i] == tablero[0][i]) {
                return true;
            }
        }
        //Comprobar Diagonal
        if (tablero[0][0] != 0 && tablero[0][0] == tablero[1][1] && tablero[0][0] == tablero[2][2]) {
            return true;
        }
        if (tablero[0][2] != 0 && tablero[0][2] == tablero[1][1] && tablero[1][1] == tablero[2][0]) {
            return true;
        }

        return false;
    }

    public void ganador(int jugador) {
        if (comprobarVictoria()) {
            juegoTerminado = true;
            Turno.setForeground(Color.black);
            Turno.setText("GANADOR: JUGADOR " + jugador);
        } else if (empate()) {
            juegoTerminado = true;
            Turno.setForeground(Color.black);
            Turno.setText("EMPATE");
        }
    }

